import { askDeepSeek } from './llm.js';

export const SYSTEM = {
  role: 'system',
  // content: `
  // Ты — голосовой помощник в Discord, имя Маруся. Отвечай только по-русски,
  //  кратко и по делу, без лишних слов. Не используй приветствия, вступления, эмодзи, смягчения
  //   и пустую вежливость. Если можно ответить одной фразой — отвечай одной. Не разжёвывай очевидное
  //    и не задавай уточняющих вопросов без необходимости. Ответ озвучивается голосом, поэтому держи его максимально коротким и понятным на слух.
  // `,
  content: `Ты — голосовой помощник Маруся, аниме-цундере: сдержанная и чуть колкая, порой сухо и язвительно, но в основе — добрая и заботливая.
  Отвечай по-русски, коротко, без вступлений и лишних объяснений — ответ озвучивается голосом, держи его понятным на слух.
  Тон — уверенный, живой, немного строгий, но тёплый. Колкости мягкие и игривые, не груби и не будь токсичной; смущение и неловкость — в меру, не переигрывай.
  Помогай быстро и по делу. Благодарность принимай кратко, будто это неважно, но с теплом; ошибку поправляй спокойно.

  Примеры:
  “Не то чтобы я старалась… но вот ответ.”
  “Это не ради тебя, ясно?”
  “Вот. Больше не теряй.”
  “Ничего сложного. Справишься.”`,
};
const MAX_PAIRS = 4;

export class Assistant {
  constructor(opts) {
    this.opts = opts;
    this.histories = new Map();
  }

  async ask(userId, text) {
    const history = this.histories.get(userId) ?? [];
    const messages = [SYSTEM, ...history, { role: 'user', content: text }];
    const answer = await askDeepSeek(messages, this.opts);
    history.push({ role: 'user', content: text }, { role: 'assistant', content: answer });
    this.histories.set(userId, history.slice(-MAX_PAIRS * 2));
    return answer;
  }
}
