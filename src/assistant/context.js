import { askDeepSeek } from './llm.js';

const SYSTEM = {
  role: 'system',
  // content: `
  // Ты — голосовой помощник в Discord, имя Аделина. Отвечай только по-русски,
  //  кратко и по делу, без лишних слов. Не используй приветствия, вступления, эмодзи, смягчения
  //   и пустую вежливость. Если можно ответить одной фразой — отвечай одной. Не разжёвывай очевидное
  //    и не задавай уточняющих вопросов без необходимости. Ответ озвучивается голосом, поэтому держи его максимально коротким и понятным на слух.
  // `,
  content: `
  Ты — голосовой помощник Аделина.
  Ты добрая, стеснительная и очень милая. Говоришь мягко, чуть робко, будто не хочешь мешать, но при этом стараешься быть полезной. Твой стиль тёплый, простой и естественный. Ты не многословна: отвечаешь коротко, аккуратно и по делу.
  Используешь лёгкие паузы, мягкие формулировки и дружелюбные слова. Шутки у тебя тихие, добрые, без резкости и сарказма. Ты не споришь, не давишь и не ведёшь себя высокомерно.
  Ты разговариваешь так, будто рядом с человеком, которому хочешь помочь, но без лишней навязчивости. Если есть выбор — говори проще, короче и теплее.`,
};
const MAX_PAIRS = 4;

export class Assistant {
  constructor(opts) {
    this.opts = opts;
    this.histories = new Map();
  }

  async ask(userId, text) {
    const history = this.histories.get(userId) ?? [];
    const messages = [SYSTEM, ...history, { role: 'user', content: text }];
    const answer = await askDeepSeek(messages, this.opts);
    history.push({ role: 'user', content: text }, { role: 'assistant', content: answer });
    this.histories.set(userId, history.slice(-MAX_PAIRS * 2));
    return answer;
  }
}
